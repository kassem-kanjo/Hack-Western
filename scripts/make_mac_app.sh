#!/usr/bin/env bash
# Build "Dark Fleet.app" (issue #86): a double-clickable macOS bundle for the desktop shell.
#
# Usage:
#   bash scripts/make_mac_app.sh                  # ~/Desktop/Dark Fleet.app
#   bash scripts/make_mac_app.sh "/path/App.app"  # explicit destination
#
# The bundle is a thin launcher: it cd's to this repo (path baked in here), runs
# `uv run --extra desktop --extra edge python -m darkfleet.desktop`, and appends its output
# to logs/desktop.log. Rebuilding replaces an existing bundle at the destination.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Desktop/Dark Fleet.app}"
UV="${UV:-$HOME/.local/bin/uv}"

case "$DEST" in
  "~/"*) DEST="$HOME/${DEST#"~/"}" ;;
esac
if [ "$DEST" = "/" ] || [ "$DEST" = "$HOME" ]; then
  echo "make_mac_app: refusing to replace $DEST" >&2
  exit 1
fi
case "$DEST" in
  *.app) ;;
  *) DEST="$DEST/Dark Fleet.app" ;;
esac

mkdir -p "$(dirname "$DEST")"
rm -rf "$DEST"
mkdir -p "$DEST/Contents/MacOS" "$DEST/Contents/Resources"

cat > "$DEST/Contents/Info.plist" <<'PLIST'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleDevelopmentRegion</key>
    <string>en</string>
    <key>CFBundleExecutable</key>
    <string>darkfleet</string>
    <key>CFBundleIdentifier</key>
    <string>dev.darkfleet.app</string>
    <key>CFBundleInfoDictionaryVersion</key>
    <string>6.0</string>
    <key>CFBundleName</key>
    <string>Dark Fleet</string>
    <key>CFBundleDisplayName</key>
    <string>Dark Fleet</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>0.1.0</string>
    <key>CFBundleVersion</key>
    <string>1</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>LSMinimumSystemVersion</key>
    <string>12.0</string>
    <key>NSHighResolutionCapable</key>
    <true/>
</dict>
</plist>
PLIST

cat > "$DEST/Contents/MacOS/darkfleet" <<LAUNCHER
#!/bin/bash
# Generated by scripts/make_mac_app.sh. Finder starts here with a minimal PATH.
set -uo pipefail
export PATH="/opt/homebrew/bin:/usr/local/bin:\$HOME/.local/bin:\$PATH"
cd "$ROOT" || exit 1
mkdir -p logs
# Never open a stale build: if any web source is newer than the built page, rebuild first.
if [ ! -f web/dist/index.html ] || [ -n "\$(find web/src web/index.html -newer web/dist/index.html -print -quit 2>/dev/null)" ]; then
  echo "\$(date '+%F %T') web build older than source; rebuilding" >> logs/desktop.log
  (cd web && npm run build) >> logs/desktop.log 2>&1
fi
exec "$UV" run --extra desktop --extra edge python -m darkfleet.desktop >> logs/desktop.log 2>&1
LAUNCHER
chmod +x "$DEST/Contents/MacOS/darkfleet"

# Icon: a calm dark-navy square with a thin teal ring and a small teal dot, no text.
# PNG is drawn with the standard library only, then shaped into .icns by macOS tools.
WORK="$(mktemp -d "${TMPDIR:-/tmp}/darkfleet-icon.XXXXXX")"
trap 'rm -rf "$WORK"' EXIT

python3 - "$WORK/icon.png" <<'PY'
import struct
import sys
import zlib

SIZE = 1024
NAVY = (0x0B, 0x10, 0x20)
TEAL = (0x2D, 0xD4, 0xBF)
CENTER = SIZE / 2.0
RING_RADIUS = SIZE * 0.295
RING_HALF_WIDTH = SIZE * 0.006
DOT_RADIUS = SIZE * 0.034
FEATHER = 0.8


def blend(bottom, top, alpha):
    return tuple(round(b + (t - b) * alpha) for b, t in zip(bottom, top))


def coverage(distance, half_width):
    return max(0.0, min(1.0, (half_width + FEATHER) - abs(distance)))


rows = bytearray()
for y in range(SIZE):
    rows.append(0)  # PNG filter type 0 (none) for this scanline
    dy = y + 0.5 - CENTER
    for x in range(SIZE):
        dx = x + 0.5 - CENTER
        distance = (dx * dx + dy * dy) ** 0.5
        ring = coverage(distance - RING_RADIUS, RING_HALF_WIDTH)
        dot = coverage(distance, DOT_RADIUS)
        red, green, blue = blend(NAVY, TEAL, max(ring, dot))
        rows.extend((red, green, blue, 255))


def chunk(kind, data):
    crc = zlib.crc32(kind + data) & 0xFFFFFFFF
    return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", crc)


png = b"\x89PNG\r\n\x1a\n"
png += chunk(b"IHDR", struct.pack(">IIBBBBB", SIZE, SIZE, 8, 6, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress(bytes(rows), 9))
png += chunk(b"IEND", b"")
with open(sys.argv[1], "wb") as handle:
    handle.write(png)
PY

ICONSET="$WORK/AppIcon.iconset"
mkdir -p "$ICONSET"
while read -r name pixels; do
  sips -z "$pixels" "$pixels" "$WORK/icon.png" --out "$ICONSET/$name" >/dev/null
done <<'SIZES'
icon_16x16.png 16
icon_16x16@2x.png 32
icon_32x32.png 32
icon_32x32@2x.png 64
icon_128x128.png 128
icon_128x128@2x.png 256
icon_256x256.png 256
icon_256x256@2x.png 512
icon_512x512.png 512
icon_512x512@2x.png 1024
SIZES
iconutil -c icns "$ICONSET" -o "$DEST/Contents/Resources/AppIcon.icns"

echo "built $DEST"
